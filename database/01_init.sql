-- Los datos son ficticios y sirven solo para demostración académica.

CREATE TABLE IF NOT EXISTS lineas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  zona VARCHAR(80) NOT NULL,
  descripcion TEXT NOT NULL,
  color VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS micros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR(20) NOT NULL UNIQUE,
  interno VARCHAR(20) NOT NULL UNIQUE,
  capacidad INTEGER NOT NULL CHECK (capacidad BETWEEN 18 AND 25),
  estado VARCHAR(30) NOT NULL CHECK (
    estado IN ('DISPONIBLE', 'EN_CIRCULACION', 'LLENO', 'FUERA_DE_SERVICIO', 'EMERGENCIA')
  ),
  autorizado BOOLEAN NOT NULL DEFAULT FALSE,
  linea_id INTEGER NOT NULL REFERENCES lineas(id)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL DEFAULT 'PASAJERO' CHECK (
    rol IN ('ADMIN', 'CONDUCTOR', 'PASAJERO', 'ESTUDIANTE')
  )
);

CREATE TABLE IF NOT EXISTS conductores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER UNIQUE REFERENCES usuarios(id) ON DELETE SET NULL,
  nombre VARCHAR(100) NOT NULL,
  apellido VARCHAR(100) NOT NULL,
  ci VARCHAR(30) NOT NULL UNIQUE,
  telefono VARCHAR(30),
  micro_id INTEGER UNIQUE REFERENCES micros(id) ON DELETE SET NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS tarifas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linea_id INTEGER NOT NULL REFERENCES lineas(id) ON DELETE CASCADE,
  categoria VARCHAR(20) NOT NULL CHECK (
    categoria IN ('GENERAL', 'ESCOLAR', 'UNIVERSITARIO')
  ),
  monto NUMERIC(10,2) NOT NULL CHECK (monto >= 0),
  vigente_desde TIMESTAMPTZ NOT NULL DEFAULT now(),
  activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS estudiantes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER UNIQUE REFERENCES usuarios(id) ON DELETE SET NULL,
  nombre VARCHAR(100) NOT NULL,
  apellido VARCHAR(100) NOT NULL,
  ci VARCHAR(30) NOT NULL UNIQUE,
  categoria VARCHAR(20) NOT NULL CHECK (categoria IN ('ESCOLAR', 'UNIVERSITARIO')),
  codigo VARCHAR(50) NOT NULL,
  correo_institucional VARCHAR(120),
  foto_url TEXT NOT NULL,
  verificado BOOLEAN NOT NULL DEFAULT FALSE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (categoria, codigo)
);

CREATE TABLE IF NOT EXISTS viajes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  micro_id INTEGER NOT NULL REFERENCES micros(id),
  conductor_id INTEGER NOT NULL REFERENCES conductores(id),
  linea_id INTEGER NOT NULL REFERENCES lineas(id),
  tipo VARCHAR(20) NOT NULL DEFAULT 'NORMAL' CHECK (tipo IN ('NORMAL', 'EMERGENCIA')),
  estado VARCHAR(20) NOT NULL DEFAULT 'EN_CURSO' CHECK (
    estado IN ('EN_CURSO', 'FINALIZADO', 'CANCELADO')
  ),
  iniciado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  finalizado_en TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS pagos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  viaje_id INTEGER NOT NULL REFERENCES viajes(id),
  monto NUMERIC(10,2) NOT NULL CHECK (monto >= 0),
  categoria VARCHAR(20) NOT NULL CHECK (
    categoria IN ('GENERAL', 'ESCOLAR', 'UNIVERSITARIO')
  ),
  metodo VARCHAR(20) NOT NULL DEFAULT 'SIMULADO' CHECK (metodo IN ('SIMULADO', 'TARJETA', 'STRIPE')),
  estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (
    estado IN ('PENDIENTE', 'CONFIRMADO', 'RECHAZADO')
  ),
  referencia VARCHAR(100) NOT NULL UNIQUE,
  stripe_sesion_id VARCHAR(255),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  confirmado_en TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS abordajes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viaje_id INTEGER NOT NULL REFERENCES viajes(id),
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  categoria VARCHAR(20) NOT NULL CHECK (
    categoria IN ('GENERAL', 'ESCOLAR', 'UNIVERSITARIO')
  ),
  pago_id INTEGER NOT NULL REFERENCES pagos(id),
  estado VARCHAR(20) NOT NULL DEFAULT 'A BORDO' CHECK (estado IN ('A BORDO', 'BAJADO')),
  registrado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS trasbordos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viaje_origen_id INTEGER NOT NULL REFERENCES viajes(id),
  viaje_destino_id INTEGER NOT NULL REFERENCES viajes(id),
  abordaje_id INTEGER NOT NULL REFERENCES abordajes(id),
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  tipo VARCHAR(20) NOT NULL DEFAULT 'NORMAL' CHECK (tipo IN ('NORMAL', 'EMERGENCIA')),
  motivo TEXT,
  pago_reutilizado BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS posiciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  micro_id INTEGER NOT NULL REFERENCES micros(id) ON DELETE CASCADE,
  lat DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
  origen VARCHAR(40) NOT NULL DEFAULT 'SIMULADO',
  registrado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notificaciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destino VARCHAR(20) NOT NULL CHECK (destino IN ('PASAJEROS', 'ADMIN', 'CONDUCTOR')),
  tipo VARCHAR(40) NOT NULL,
  mensaje TEXT NOT NULL,
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE,
  leida BOOLEAN NOT NULL DEFAULT FALSE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS auditoria (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  accion VARCHAR(120) NOT NULL,
  entidad VARCHAR(60) NOT NULL,
  entidad_id INTEGER,
  detalle JSONB,
  usuario VARCHAR(80),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_posiciones_micro_fecha ON posiciones (micro_id, registrado_en DESC);
CREATE INDEX IF NOT EXISTS idx_abordajes_viaje_estado ON abordajes (viaje_id, estado);
CREATE INDEX IF NOT EXISTS idx_pagos_usuario ON pagos (usuario_id, creado_en DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tarifa_activa ON tarifas (linea_id, categoria) WHERE activa;
CREATE UNIQUE INDEX IF NOT EXISTS idx_viaje_activo_micro ON viajes (micro_id) WHERE estado = 'EN_CURSO';

